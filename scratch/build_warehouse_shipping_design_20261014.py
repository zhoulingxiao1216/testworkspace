def yaml_text(obj, level=0):
    pad='  '*level
    if isinstance(obj, dict):
        lines=[]
        for k,v in obj.items():
            if isinstance(v, (dict,list)) and v:
                lines.append(pad+str(k)+':\n'+yaml_text(v,level+1))
            else:
                lines.append(pad+str(k)+': '+json.dumps(v,ensure_ascii=False))
        return '\n'.join(lines)
    if isinstance(obj,list):
        lines=[]
        for v in obj:
            if isinstance(v,(dict,list)) and v:
                lines.append(pad+'-\n'+yaml_text(v,level+1))
            else:
                lines.append(pad+'- '+json.dumps(v,ensure_ascii=False))
        return '\n'.join(lines)
    return pad+json.dumps(obj,ensure_ascii=False)

